#' \describe{
#'   \item{SampleID}{Sample identifier.}
#'   \item{CD11c, CD69, CD3, PDL1, CD8, CD45RA}{Intensity cutoffs per marker.}
#' }
#'
#' @docType data
#' @usage data(mif_cutoffs)
#' @keywords datasets
#' @source Simulated for examples and tests; generated by
#'   `data-raw/make_example_data.R`.
"mif_cutoffs"

#' Example cell-type classification rules
#'
#' Classification rules used to assign cell types from marker statuses, in the
