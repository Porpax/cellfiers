#'   \item{CellType}{Cell type label.}
#'   \item{CD11c, CD3, CD8, PDL1, CD45RA, CD69}{Required status
#'     (`"+"`/`"-"`/`NA`).}
#' }
#'
#' @docType data
#' @usage data(mif_rules)
#' @keywords datasets
#' @source Simulated for examples and tests; generated by
#'   `data-raw/make_example_data.R`.
"mif_rules"

