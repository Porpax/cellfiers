#' Example mIF single-cell data (QuPath style)
#'
#' Simulated multiplex immunofluorescence single-cell data mimicking a QuPath
#' classification export. Contains 3 samples (C1001, C1002, C1003) and 450
#' cells. Cells live either inside the `"SLN_Tregion"` parent annotation or
#' outside it (`"outline"`). The six intensity columns hold mean fluorescence
#' intensities for the channels used by the example marker map.
#'
#' @format A data frame with 450 rows and 15 columns:
#' \describe{
#'   \item{sample_id}{Sample identifier.}
#'   \item{cell_id}{Unique cell identifier (`<sample>_<index>`).}
#'   \item{Image}{Image name (QuPath style).}
#'   \item{Classification}{QuPath classification (empty in the example).}
#'   \item{Parent}{Parent annotation, e.g. `SLN_Tregion`.}
#'   \item{Centroid X um, Centroid Y um}{Cell centroid coordinates in
#'     micrometres. Real QuPath columns using the micro sign are also supported.}
#'   \item{Nucleus: Area}{Nucleus area.}
#'   \item{Cell: Opal 780 mean, Cell: Opal 570 mean, Cell: Opal 690 mean,
#'     Cell: Opal 480 mean, Cell: Opal 620 mean, Cell: Opal 520 mean}{
#'     Mean fluorescence intensities of the six channels.}
#'   \item{Nucleus/Cell area ratio}{Nucleus to cell area ratio.}
#' }
#'
#' @docType data
#' @usage data(mif_cells)
#' @keywords datasets
#' @source Simulated for examples and tests; generated by
#'   `data-raw/make_example_data.R`.
"mif_cells"

#' Example fluorescence channel cutoffs
